#!/usr/bin/env bash
# SRC_GPU-SURF — general direct standalone fluid calibrator (0493w1 family)
# Selectable path: SRC or production Q6-G-F. Measures TG viscosity and self diffusion; sound speed is qualified only for SRC.
# One file. No repo script dependency. No source modification. No build.
set -euo pipefail
SELF="$(readlink -f "${BASH_SOURCE[0]}")"
SELF_DIR="$(cd "$(dirname "$SELF")" && pwd)"
usage(){ cat <<'USAGE'
General fluid characterization — direct standalone 0493w1 family

Usage:
  bash calibrate_src_fluid_0493w1_standalone.sh
  bash calibrate_src_fluid_0493w1_standalone.sh --preflight
  bash calibrate_src_fluid_0493w1_standalone.sh --analyze-only
  bash calibrate_src_fluid_0493w1_standalone.sh --check

Calibration path:
  CALIBRATION_PATH=src            # default
  CALIBRATION_PATH=src-q6-g-f     # production Q6-G-F path

Path-aware default measurements:
  src        -> CALIBRATION_EXPERIMENTS="tg sound msd"
  src-q6-g-f -> CALIBRATION_EXPERIMENTS="tg msd"

  tg    : canonical 0493w1 Taylor-Green viscosity nu on the selected path
  sound : standing density wave / cumulative longitudinal regression
          SRC: qualified c_s; Q6-G-F: diagnostic only, c_s NOT qualified
  msd   : persistent-slot unwrapped COM-corrected MSD for D_self on the selected path

The combined output reports Sc=nu/D_self and, if CHARACTERISTIC_U/L are positive, Re and mass Peclet number. Mach is reported only when sound speed is qualified (SRC).

Fluid overrides:
  GAMMA=20
  ROTATION_ANGLE_DEG=90
  KBT=0.125
  PARTICLE_MASS=1
  CELL_SIZE=0.00390625
  DT_OVERRIDE=0.002
  # or LAMBDA_OVER_H=0.48


Q6-G-F production defaults (overridable):
  PROJECTION_BACKEND=cuda
  PROJECTION_OPERATOR=auto_fv_cg
  PROJECTION_TOLERANCE=1e-5
  PROJECTION_MAX_ITERATIONS=2500
  Q6_GF_DENSITY_RELAXATION_TIME=0.25
  Q6_GF_DENSITY_COMPRESSION_THRESHOLD_PARTICLES=3
  Q6_GF_DENSITY_TRACTION_THRESHOLD_PARTICLES=6
  Q6_GF_DENSITY_TRACTION_GAIN=1.0
  Q6_GF_MIN_FILL_FRACTION=0.10

Taylor-Green defaults:
  NX=64 NY=64
  TG_MODE_X=1 TG_MODE_Y=1
  TG_AMPLITUDE=<auto: 0.1*sqrt(2*kBT/m)>
  TG_TIME=4.0 TG_DUMP_COUNT=80
  SEEDS=4931301,4931302,4931303

Sound defaults:
  SOUND_NX=64 SOUND_NY=16 SOUND_MODE_X=1
  SOUND_DENSITY_AMPLITUDE=0.08
  SOUND_CYCLES=3.4          # schedules observation only; does not enter c_s fit
  SOUND_DUMP_COUNT=120
  SOUND_REPLICATES=<auto max(3,ceil(240/gamma))>
  # SOUND_TIME=<explicit physical duration> overrides SOUND_CYCLES

MSD defaults:
  MSD_NX=NX MSD_NY=NY
  MSD_TIME=5.0 MSD_DUMP_COUNT=60
  MSD_SAMPLE_PARTICLES=20000
  MSD_SEEDS=SEEDS

Runtime:
  BIN=build/src_mpcd_base_cuda_q6_resident_livevis_0486
  ROOT=/path/to/SRC_GPU-SURF
  RUN_ROOT=runs/src_fluid_0493w1_standalone
  LIVE_PROGRESS=1
  SKIP_EXISTING=1
  CLEAN_RUN_ROOT=1
  MAX_DUMP_GB=5.0

Examples:
  # Complete SRC characterization
  CALIBRATION_PATH=src GAMMA=8 ROTATION_ANGLE_DEG=120 LAMBDA_OVER_H=.72 \
  CLEAN_RUN_ROOT=1 LIVE_PROGRESS=1 \
  bash scripts/calibrate_fluid_0493w1_standalone.sh

  # Q6-G-F characterization: TG + MSD by default
  CALIBRATION_PATH=src-q6-g-f \
  CLEAN_RUN_ROOT=1 LIVE_PROGRESS=1 \
  bash scripts/calibrate_fluid_0493w1_standalone.sh

  # Q6-G-F viscosity ensemble only
  CALIBRATION_PATH=src-q6-g-f CALIBRATION_EXPERIMENTS=tg \
  SEEDS=493201,593201,693201,793201 \
  bash scripts/calibrate_fluid_0493w1_standalone.sh
USAGE
}
MODE=run
case "${1:-}" in
  '') ;;
  --preflight) MODE=preflight; shift ;;
  --analyze-only) MODE=analyze; shift ;;
  --check) MODE=check; shift ;;
  -h|--help) usage; exit 0 ;;
  *) echo "[src-fluid] ERROR unknown argument: $1" >&2; usage >&2; exit 2 ;;
esac
[[ $# -eq 0 ]] || { echo "[src-fluid] ERROR unexpected arguments: $*" >&2; exit 2; }
ROOT="${ROOT:-$PWD}"; ROOT="$(cd "$ROOT" && pwd)"; cd "$ROOT"
for c in bash python3 tar base64 sha256sum awk grep;do command -v "$c" >/dev/null||{ echo "[src-fluid] ERROR missing command: $c" >&2;exit 127;};done
python3 - <<'PY'
try: import numpy
except Exception as e: raise SystemExit(f'[src-fluid] ERROR NumPy unavailable: {e}')
print(f'[src-fluid] Python/NumPy OK ({numpy.__version__})')
PY
resolve_binary(){ if [[ -n "${BIN:-}" ]];then [[ -x "$BIN" ]]||{ echo "[src-fluid] ERROR BIN not executable: $BIN" >&2;return 2;};printf '%s\n' "$BIN";return;fi;local b=build/src_mpcd_base_cuda_q6_resident_livevis_0486;[[ -x "$b" ]]||{ echo '[src-fluid] ERROR solver binary not resolved; set BIN=' >&2;return 2;};printf '%s\n' "$b"; }
BIN="$(resolve_binary)";export ROOT BIN AUTO_BUILD=0 BUILD_IF_STALE=0 FORCE_BUILD=0
TMP="$(mktemp -d "${TMPDIR:-/tmp}/src_fluid_0493w1.XXXXXX")";trap 'rm -rf "$TMP"' EXIT HUP INT TERM
awk '/^__SRC_FLUID_0493W1_PAYLOAD_BELOW__$/ {f=1; next} f {print}' "$SELF" > "$TMP/payload.b64"
base64 -d "$TMP/payload.b64" > "$TMP/payload.tar.gz"
EXPECTED_PAYLOAD_SHA='19170202c2a0eb9434fb6d9b093e8a4c0271c47c76b18df9438dd00841f9c937';ACTUAL_PAYLOAD_SHA="$(sha256sum "$TMP/payload.tar.gz"|awk '{print $1}')"
[[ "$ACTUAL_PAYLOAD_SHA" == "$EXPECTED_PAYLOAD_SHA" ]]||{ echo '[src-fluid] ERROR payload checksum mismatch' >&2;exit 3;}
tar -xzf "$TMP/payload.tar.gz" -C "$TMP";TOOLS="$TMP/scripts";export SRC_FLUID_TOOLS_DIR="$TOOLS" SRC_FLUID_PAYLOAD_SHA256="$ACTUAL_PAYLOAD_SHA" CALIBRATOR_STANDALONE_SHA256="$(sha256sum "$SELF"|awk '{print $1}')"

self_test(){
  python3 -m py_compile "$TOOLS"/*.py
  if grep -RqE 'src_mpcd_run_common_0434|suite_' "$TOOLS";then echo '[src-fluid] ERROR shared runner dependency found in payload' >&2;return 3;fi
  PYTHONPATH="$TOOLS" python3 - "$TOOLS" "$TMP" <<'PY'
import math,subprocess,sys,struct
from pathlib import Path
import numpy as np
T=Path(sys.argv[1]);R=Path(sys.argv[2]);sys.path.insert(0,str(T))
import analyze_0493w1_src_fluid_calibrator as a
# TG synthetic decay
rt=R/'self_tg';(rt/'tg'/'output').mkdir(parents=True)
nu=.01;dt=.02;L=1.;k2=2*(2*math.pi/L)**2;A0=.1;G=T/'generate_0493w1_src_fluid_calibrator_states.py'
for step in range(0,101,10):
 A=A0*math.exp(-nu*k2*step*dt);o=rt/'tg'/'output'/f'state_step_{step:08d}.smpcd'
 subprocess.check_call(['python3',str(G),'--case','tg','--output',str(o),'--Lx','1','--Ly','1','--Nx','16','--Ny','16','--gamma','4','--dt',str(dt),'--kBT','1e-8','--mass','1','--seed','17','--tg-mode-x','1','--tg-mode-y','1','--tg-amplitude',repr(A),'--sound-mode-x','1','--sound-density-amplitude','.08'],stdout=subprocess.DEVNULL)
ns=type('N',(),{'root':rt,'Lx':1.,'Ly':1.,'tg_mode_x':1,'tg_mode_y':1,'dt':dt});_,tr=a.analyze_tg(ns);te=abs(tr['nu']-nu)/nu
if te>.02:raise SystemExit(f'TG self-test relerr={te}')
# Longitudinal regression synthetic ODE
cs=.35;nul=.0012;L=.25;k=2*math.pi/L;dt=.002;n=1201;rho=1+0j;u=0+0j;ts=[];rs=[];us=[]
def f(r,u):return -1j*k*u,-1j*k*cs*cs*r-nul*k*k*u
for j in range(n):
 ts.append(j*dt);rs.append(rho);us.append(u)
 if j==n-1:break
 q1=f(rho,u);q2=f(rho+.5*dt*q1[0],u+.5*dt*q1[1]);q3=f(rho+.5*dt*q2[0],u+.5*dt*q2[1]);q4=f(rho+dt*q3[0],u+dt*q3[1]);rho+=dt*(q1[0]+2*q2[0]+2*q3[0]+q4[0])/6;u+=dt*(q1[1]+2*q2[1]+2*q3[1]+q4[1])/6
sr=a.fit_longitudinal_hydrodynamics(np.array(ts),np.array(rs),np.array(us),k);se=abs(sr['soundSpeed']-cs)/cs
if se>.01:raise SystemExit(f'sound self-test relerr={se}')
# MSD synthetic Brownian trajectories
rm=R/'self_msd';(rm/'msd'/'output').mkdir(parents=True);rng=np.random.default_rng(1234);N=4096;D=.02;dt=.01;x=rng.random(N);y=rng.random(N);z=np.zeros(N);typ=np.zeros(N,dtype=np.uint32);mass=np.ones(N);role=np.ones(N,dtype=np.uint8)
def write(step):
 p=rm/'msd'/'output'/f'state_step_{step:08d}.smpcd'
 with p.open('wb') as f0:
  magic=b'SRCMPCD_STATE'+b'\0'*(16-len('SRCMPCD_STATE'));f0.write(magic);f0.write(struct.pack('<IIIIQIIII',2,0x01020304,2,1,N,1,1,8,4));f0.write(struct.pack('<8Q',1,1,0,0,0,0,0,0))
  for arr,dtype in ((x,'<f8'),(y,'<f8'),(z,'<f8'),(z,'<f8'),(typ,'<u4'),(mass,'<f8'),(role,'u1')):np.asarray(arr,dtype=dtype).tofile(f0)
write(0);last=0
for step in range(10,201,10):
 sig=math.sqrt(2*D*(step-last)*dt);x[:]=(x+rng.normal(0,sig,N))%1;y[:]=(y+rng.normal(0,sig,N))%1;write(step);last=step
mn=type('N',(),{'root':rm,'dt':dt,'msd_Lx':1.,'msd_Ly':1.,'msd_sample_particles':4000});_,mr=a.analyze_msd(mn);me=abs(mr['selfDiffusion']-D)/D
if me>.12:raise SystemExit(f'MSD self-test relerr={me}')
print(f'[src-fluid] self-test TG relerr={te:.3%}; sound relerr={se:.3%}; MSD relerr={me:.3%}')
PY
}
case "$MODE" in
 check)
  echo "[src-fluid] root=$ROOT";echo "[src-fluid] binary=$BIN";echo '[src-fluid] integration=direct-standalone paths=src,src-q6-g-f'
  self_test
  CALIBRATION_PATH=src CALIBRATION_EXPERIMENTS=tg SRC_FLUID_MODE=preflight RUN_ROOT="$TMP/preflight_src" CLEAN_RUN_ROOT=1 bash "$TOOLS/run_src_fluid_complete_direct.sh"
  CALIBRATION_PATH=src-q6-g-f CALIBRATION_EXPERIMENTS=tg SRC_FLUID_MODE=preflight RUN_ROOT="$TMP/preflight_q6gf" CLEAN_RUN_ROOT=1 bash "$TOOLS/run_src_fluid_complete_direct.sh"
  echo '[src-fluid] CHECK PASS src+q6-g-f'
  ;;
 preflight) SRC_FLUID_MODE=preflight bash "$TOOLS/run_src_fluid_complete_direct.sh" ;;
 analyze) SRC_FLUID_MODE=analyze bash "$TOOLS/run_src_fluid_complete_direct.sh" ;;
 run) SRC_FLUID_MODE=run bash "$TOOLS/run_src_fluid_complete_direct.sh" ;;
esac
exit $?

