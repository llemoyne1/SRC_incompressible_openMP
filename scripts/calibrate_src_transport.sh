#!/usr/bin/env bash
# SRC_GPU-SURF application-scale transverse transport calibrator — standalone v2.1
# One file. No C++/CUDA source modification. No dependency on historical x13 scripts.
set -euo pipefail

SELF="$(readlink -f "${BASH_SOURCE[0]}")"
SELF_DIR="$(cd "$(dirname "$SELF")" && pwd)"

usage(){
cat <<'USAGE'
Application-scale SRC transport calibrator — standalone v2.1

Normal use:
  CHARACTERISTIC_L=<hydrodynamic length> \
  CHARACTERISTIC_U=<optional velocity> \
  bash scripts/calibrate_src_transport.sh

The calibrator measures nu_eff at the requested application scale L and, in the
same simulations, measures L/2 and L/4 when resolution allows. The primary fit
is performed on the signed ensemble-mean modal decay; noisy individual fits are
QC only. Scale dependence is reported separately and never invalidates a reliable
measurement at L.

Modes:
  --preflight      audit path and print exact planned cost; no solver run
  --analyze-only   analyze an existing RUN_ROOT
  --check          dependency/self-test plus SRC and Q6-G-F preflights

Main inputs:
  CALIBRATION_PATH=src|src-q6|src-q6-g-f   (default src)
  CHARACTERISTIC_L=<L>                     recommended application scale
  CHARACTERISTIC_U=<U>                     optional; enables Re_eff=UL/nu_eff
  CALIBRATION_BUDGET=quick|standard|strict (default standard)
  BIN=build/<exact solver binary>           optional explicit binary

Microscopic fluid overrides:
  GAMMA, ROTATION_ANGLE_DEG, LAMBDA_OVER_H, DT_OVERRIDE, KBT,
  CELL_SIZE, PARTICLE_MASS, thermostat/grid-shift settings.

Normal standard preset:
  3 independent seeds, Nx=8, target 0.45 e-fold at L, ~48 state dumps/run,
  live visualization OFF, and a bounded particle-step budget.

Advanced overrides remain possible (SEEDS, SHEAR_NX, SHEAR_TARGET_EFOLDS,
MAX_TARGET_CELLS, MAX_PARTICLE_STEPS), but a normal user does not need them.
USAGE
}

MODE=run
case "${1:-}" in
  '') ;;
  --preflight) MODE=preflight;shift;;
  --analyze-only) MODE=analyze;shift;;
  --check) MODE=check;shift;;
  -h|--help) usage;exit 0;;
  *) echo "[src-transport-v2.1] ERROR unknown argument: $1" >&2;usage >&2;exit 2;;
esac
[[ $# -eq 0 ]] || { echo "[src-transport-v2.1] ERROR unexpected arguments: $*" >&2;exit 2; }

resolve_root(){
  if [[ -n "${ROOT:-}" ]];then (cd "$ROOT" && pwd);return;fi
  if [[ -d "$PWD/src" && -d "$PWD/scripts" ]];then pwd;return;fi
  if [[ -d "$SELF_DIR/../src" && -d "$SELF_DIR/../scripts" ]];then (cd "$SELF_DIR/.." && pwd);return;fi
  echo '[src-transport-v2.1] ERROR cannot locate SRC_GPU-SURF repository; run from repository or export ROOT=/path/to/repo' >&2;return 2
}
ROOT="$(resolve_root)";cd "$ROOT"
for cmd in bash python3 tar base64 sha256sum awk grep sed /usr/bin/time;do
  [[ "$cmd" == /* ]] && { [[ -x "$cmd" ]] || { echo "[src-transport-v2.1] ERROR missing $cmd" >&2;exit 127; };continue; }
  command -v "$cmd" >/dev/null 2>&1 || { echo "[src-transport-v2.1] ERROR missing command: $cmd" >&2;exit 127; }
done
python3 - <<'PY'
try:
 import numpy
except Exception as e:raise SystemExit(f'[src-transport-v2.1] ERROR NumPy unavailable: {e}')
print(f'[src-transport-v2.1] Python/NumPy OK ({numpy.__version__})')
PY

resolve_binary(){
 if [[ -n "${BIN:-}" ]];then [[ -x "$BIN" ]]||{ echo "[src-transport-v2.1] ERROR BIN not executable: $BIN" >&2;return 2;};printf '%s\n' "$BIN";return;fi
 local canonical='build/src_mpcd_base_cuda_q6_resident_livevis_0486'
 if [[ -x "$canonical" ]];then printf '%s\n' "$canonical";return;fi
 local -a cand=();while IFS= read -r f;do [[ -x "$f" ]]&&cand+=("$f");done < <(find build -maxdepth 1 -type f -name 'src_mpcd_base_cuda_q6_resident_livevis_*' -print 2>/dev/null|sort)
 if (( ${#cand[@]}==1 ));then printf '%s\n' "${cand[0]}";return;fi
 echo "[src-transport-v2.1] ERROR binary not resolved; set BIN=build/<exact_binary> (found ${#cand[@]} candidates)" >&2;return 2
}
BIN="$(resolve_binary)";export BIN ROOT AUTO_BUILD=0 BUILD_IF_STALE=0 FORCE_BUILD=0

TOOLS_TMP="$(mktemp -d "${TMPDIR:-/tmp}/src_transport_v21.XXXXXX")"
cleanup(){ rm -rf "$TOOLS_TMP"; };trap cleanup EXIT HUP INT TERM
awk '/^__SRC_TRANSPORT_V21_PAYLOAD_BELOW__$/ {f=1;next} f {print}' "$SELF" > "$TOOLS_TMP/payload.b64"
base64 -d "$TOOLS_TMP/payload.b64" > "$TOOLS_TMP/payload.tar.gz"
EXPECTED_PAYLOAD_SHA='537957c40527ae7a7d9416b753b708889f4781548d04176fbacc1411f4b5ba09'
ACTUAL_PAYLOAD_SHA="$(sha256sum "$TOOLS_TMP/payload.tar.gz"|awk '{print $1}')"
[[ "$ACTUAL_PAYLOAD_SHA" == "$EXPECTED_PAYLOAD_SHA" ]] || { echo '[src-transport-v2.1] ERROR embedded payload checksum mismatch' >&2;exit 3; }
tar -xzf "$TOOLS_TMP/payload.tar.gz" -C "$TOOLS_TMP"
TOOLS="$TOOLS_TMP/scripts";export SRC_TRANSPORT_TOOLS_DIR="$TOOLS" SRC_TRANSPORT_PAYLOAD_SHA256="$ACTUAL_PAYLOAD_SHA" CALIBRATOR_STANDALONE_SHA256="$(sha256sum "$SELF"|awk '{print $1}')"

case "$MODE" in
 check)
   echo "[src-transport-v2.1] root=$ROOT";echo "[src-transport-v2.1] binary=$BIN";echo "[src-transport-v2.1] selfSha256=$CALIBRATOR_STANDALONE_SHA256";echo "[src-transport-v2.1] payloadSha256=$ACTUAL_PAYLOAD_SHA"
   python3 "$TOOLS/analyze_application_multimode_transport.py" --self-test
   PREFLIGHT_ONLY=1 PREFLIGHT_FIRST_SEED_ONLY=1 CALIBRATION_BUDGET=quick TARGET_WAVELENGTH_CELLS=96 CHARACTERISTIC_L=-1 CALIBRATION_PATH=src RUN_ROOT="$TOOLS_TMP/check_src" bash "$TOOLS/calibrate_application_transport_embedded.sh"
   PREFLIGHT_ONLY=1 PREFLIGHT_FIRST_SEED_ONLY=1 CALIBRATION_BUDGET=quick TARGET_WAVELENGTH_CELLS=96 CHARACTERISTIC_L=-1 CALIBRATION_PATH=src-q6-g-f RUN_ROOT="$TOOLS_TMP/check_q6gf" bash "$TOOLS/calibrate_application_transport_embedded.sh"
   echo '[src-transport-v2.1] PASS dependencies + multimode fit self-test + SRC/Q6-G-F preflights'
   ;;
 preflight) PREFLIGHT_ONLY=1 bash "$TOOLS/calibrate_application_transport_embedded.sh";;
 analyze) ANALYZE_ONLY=1 bash "$TOOLS/calibrate_application_transport_embedded.sh";;
 run) bash "$TOOLS/calibrate_application_transport_embedded.sh";;
esac
exit $?

